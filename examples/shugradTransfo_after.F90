!#PYFT transfo: --shugradTransfo
MODULE MODFOO
  CONTAINS
  SUBROUTINE SUBFOO
USE MODE_SHUMAN_PHY, ONLY: MXM2D_PHY, MZF_PHY, MZM_PHY
    REAL, DIMENSION(D%NIJT, D%NKT) :: P1, P2, P3, P4, P5, P6, P8, P9
    REAL, DIMENSION(D%NIJT) :: P7, P10
INTEGER :: JIJ
INTEGER :: JK
REAL, DIMENSION(D%NIJT, D%NKT) :: ZWORKSHUGRAD_3D_1
REAL, DIMENSION(D%NIJT, D%NKT) :: ZWORKSHUGRAD_3D_2
    REAL, DIMENSION(D%NIJT, D%NKT) :: P11, P12, P13, P14, P15, P16, P17, P18, P19, P20, P21, P22

    ! Fast path

    CALL MZM_PHY(D, P2, P1)

    CALL MZM_PHY(D, P4, P3)

    CALL MXM2D_PHY(D, P6(:,IKE+1), P5(:,IKE+1))

    CALL MXM2D_PHY(D, P8(:,IKE+1), P7)

    CALL MXM2D_PHY(D, P10, P9(:,IKE+1))

    ! Non fast path

    !$acc kernels
    !$mnh_expand_array(JIJ=IIB:IIE, JK=1:D%NKT)
    ZWORKSHUGRAD_3D_1(IIB:IIE, 1:D%NKT)=P12(IIB:IIE, 1:D%NKT)+P13(IIB:IIE, 1:D%NKT)
    !$mnh_end_expand_array(JIJ=IIB:IIE, JK=1:D%NKT)
    !$acc end kernels
    CALL MZM_PHY(D, ZWORKSHUGRAD_3D_1, P11)

    CALL MZM_PHY(D, P16, ZWORKSHUGRAD_3D_1)
    CALL MZM_PHY(D, P15, ZWORKSHUGRAD_3D_2)
    !$acc kernels
    !$mnh_expand_array(JIJ=1:D%NIJT, JK=1:D%NKT)
    P14(1:D%NIJT, 1:D%NKT)=ZWORKSHUGRAD_3D_2(1:D%NIJT, 1:D%NKT)+ZWORKSHUGRAD_3D_1(1:D%NIJT, 1:D%NKT)+P17(1:D%NIJT, 1:D%NKT)
    !$mnh_end_expand_array(JIJ=1:D%NIJT, JK=1:D%NKT)
    !$acc end kernels
    CALL MZF_PHY(D, P19, ZWORKSHUGRAD_3D_1)
    !$acc kernels
    !$mnh_expand_array(JIJ=1:D%NIJT, JK=1:D%NKT)
    ZWORKSHUGRAD_3D_2(1:D%NIJT, 1:D%NKT)=ZWORKSHUGRAD_3D_1(1:D%NIJT, 1:D%NKT)+P20(1:D%NIJT, 1:D%NKT)
    !$mnh_end_expand_array(JIJ=1:D%NIJT, JK=1:D%NKT)
    !$acc end kernels
    CALL MZM_PHY(D, ZWORKSHUGRAD_3D_2, P18)

    CALL MZF_PHY(D, P22, ZWORKSHUGRAD_3D_1)
    CALL MZM_PHY(D, ZWORKSHUGRAD_3D_1, P21)

    ! IF

    IF(.TRUE.) CALL MZM_PHY(D, P2, P1)

    IF(.TRUE.) THEN
      CALL MZF_PHY(D, P22, ZWORKSHUGRAD_3D_1)
      CALL MZM_PHY(D, ZWORKSHUGRAD_3D_1, P21)
    END IF

  END SUBROUTINE SUBFOO
END MODULE MODFOO
